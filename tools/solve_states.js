// Solves each real-state layout for both parties with the game's own solver and
// writes states.js, which the page loads before game.js.
// Usage: node tools/solve_states.js layouts.json states.js
const fs = require('fs');
const path = require('path');
const g = require(path.join(__dirname, '..', 'game.js'));

const layouts = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const out = [];
for (const s of layouts) {
  const entry = { ...s, parties: {} };
  for (const party of ['dem', 'rep']) {
    const tiles = g.buildMaskedGrid(s.cols, s.rows, s.cells);
    tiles.forEach((t, i) => {
      t.pop = s.cells[i][2];
      t.lean = party === 'dem' ? s.cells[i][3] : Math.round((100 - s.cells[i][3]) * 10) / 10;
    });
    const n = s.seats;
    const majority = Math.floor(n / 2) + 1;
    const total = tiles.reduce((a, t) => a + t.pop, 0);
    const ideal = total / n;
    const rand = g.mulberry32(s.code.charCodeAt(0) * 1000 + s.code.charCodeAt(1) + (party === 'dem' ? 0 : 7));
    const samples = g.sampleLegalPlans(tiles, n, ideal, rand, g.TOLERANCE, 150, 60000, 2, 0.01);
    if (samples.length < 50) throw new Error(`${s.code} ${party}: only ${samples.length} legal random plans`);
    const best = g.findBestPlan(tiles, n, ideal, samples, rand, g.TOLERANCE, 120000);
    // Target: the fewest seats (at least a majority) that no more than 10% of random
    // legal plans reach, capped at the best the solver found.
    const reach = (k) => samples.filter((x) => x.seats >= k).length / samples.length;
    let target = Math.min(majority, best.seats);
    while (target < best.seats && reach(target) > 0.1) target++;
    const winFraction = reach(target);
    const randomSeats = samples.map((x) => x.seats).reduce((a, b) => a + b, 0) / samples.length;

    // Realistic mode: the most seats the solver can win with at least a 75% chance.
    const uncSeed = s.code.charCodeAt(0) * 131 + s.code.charCodeAt(1);
    const unc = g.buildUncertainty(tiles, uncSeed);
    let realisticTarget = target;
    let robust = null;
    let robustChance = 0;
    for (; realisticTarget >= 1; realisticTarget--) {
      const k = realisticTarget;
      const starts = samples
        .map((x) => ({ plan: x.plan, kth: g.kthShare(g.planShares(tiles, x.plan, n), k) }))
        .sort((a, b) => b.kth - a.kth).slice(0, 3).map((x) => x.plan);
      starts.unshift(best.plan);
      robust = g.findRobustPlan(tiles, n, ideal, k, starts, rand, g.TOLERANCE, 120000);
      robustChance = robust ? g.simulatePlan({ tiles, cfg: { districts: n }, target: k, unc }, robust.plan).pTarget : 0;
      if (robustChance >= 0.75) break;
    }
    const realMap = { tiles, cfg: { districts: n }, target: realisticTarget, unc };
    const realisticFraction = samples.filter((x) => g.simulatePlan(realMap, x.plan).pTarget >= g.PASS_PROBABILITY).length / samples.length;

    const st = g.computeStats(tiles, best.plan, n, ideal);
    if (!st.every((x) => x.popOk && x.connected)) throw new Error(`${s.code} ${party}: illegal solution`);
    entry.parties[party] = {
      target, majority, maxSeats: best.seats, winFraction, randomSeats: Math.round(randomSeats * 10) / 10,
      sampleCount: samples.length, solution: best.plan,
      uncSeed, realisticTarget, robustSolution: robust ? robust.plan : best.plan,
      robustChance: Math.round(robustChance * 1000) / 1000, realisticFraction,
    };
    console.log(`${s.code} ${party}: best ${best.seats}/${n} (majority ${majority}), random plans avg ${randomSeats.toFixed(1)} seats, ` +
      `target ${target} (${(winFraction * 100).toFixed(0)}% of random plans reach it); realistic target ${realisticTarget} ` +
      `at ${(robustChance * 100).toFixed(0)}% (${(realisticFraction * 100).toFixed(0)}% of random plans reach 70%)`);
  }
  out.push(entry);
}
const header = '// Generated by tools/solve_states.js from tools/build_states.py output. Do not edit by hand.\n' +
  '// Data: 2020 presidential results by county (github.com/tonmcg/US_County_Level_Election_Results_08-20)\n' +
  '// and 2019 Census Bureau county population estimates (github.com/evangambit/JsonOfCounties).\n';
fs.writeFileSync(process.argv[3], header + 'const STATE_DATA = ' + JSON.stringify(out) + ';\n' +
  "if (typeof module !== 'undefined') module.exports = { STATE_DATA };\n");
